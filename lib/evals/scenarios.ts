export function selectScenarios(opts: { only?: string[]; category?: string }): ScenarioDef[] {
  let list = SCENARIOS;
  if (opts.only?.length) list = list.filter((s) => opts.only?.includes(s.id));
  if (opts.category) list = list.filter((s) => s.category === opts.category);
  return list;
}
